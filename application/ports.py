"""Порты (интерфейсы) драйверов и хранилищ."""
from __future__ import annotations

from typing import Callable, List, Optional, Protocol

import domain


class SessionDriver(Protocol):
    def set_event_sink(self, sink: Callable[[domain.OutputEvent], None]) -> None: ...
    def open(self, config: domain.SessionConfig) -> domain.SessionId: ...
    def send(self, request: domain.CommandRequest) -> None: ...
    def close(self) -> None: ...
    
    def complete(
        self, session_id: domain.SessionId, text: str
    ) -> List[str]:
        """Вернуть варианты автодополнения последнего токена в text.

        Пустой список означает, что дополнение недоступно.
        Реализация не должна ничего запускать у пользователя и не должна
        попадать в журнал.
        """
        ...

    def write_input(self, session_id: domain.SessionId, data: str) -> None:
        """Байты в PTY текущей команды. Не команда и не запись журнала."""
        ...

    def resize(self, session_id: domain.SessionId, cols: int, rows: int) -> None:
        """Новый размер PTY текущей команды."""
        ...

    def cancel(self, session_id: domain.SessionId) -> None:
        """Остановить текущую команду. Сессию не закрывает."""
        ...


class SessionCatalog(Protocol):
    def save(self, info: domain.SessionInfo) -> None: ...
    def list(self) -> List[domain.SessionInfo]: ...
    def get(self, session_id: domain.SessionId) -> Optional[domain.SessionInfo]: ...
    def delete(self, session_id: domain.SessionId) -> None: ...


class JournalRepository(Protocol):
    def create(self, session_id: domain.SessionId, password: str) -> None: ...
    def unlock(self, session_id: domain.SessionId, password: str) -> None: ...
    def lock(self, session_id: domain.SessionId) -> None: ...
    def is_unlocked(self, session_id: domain.SessionId) -> bool: ...
    def next_sequence(self, session_id: domain.SessionId) -> int: ...
    def append(self, event: domain.TranscriptEvent) -> None: ...
    def get_by_session(
        self, session_id: domain.SessionId
    ) -> List[domain.TranscriptEvent]: ...
    def delete(self, session_id: domain.SessionId) -> None: ...


class LlmProfileStore(Protocol):
    def list(self) -> List[domain.LlmProfile]: ...
    def get(self, profile_id: domain.ProfileId) -> Optional[domain.LlmProfile]: ...
    def save(self, profile: domain.LlmProfile) -> None: ...
    def delete(self, profile_id: domain.ProfileId) -> None: ...


class LlmClient(Protocol):
    def list_models(self, profile: domain.LlmProfile) -> List[str]: ...
    def complete(
        self, profile: domain.LlmProfile, messages: List[tuple]
    ) -> str: ...
    def complete_turn(
        self,
        profile: domain.LlmProfile,
        messages: list,
        tools: list,
        allow_tools: bool = True,
    ) -> domain.LlmTurn: ...


DriverFactory = Callable[[domain.ProviderType], SessionDriver]
EventCallback = Callable[[domain.TranscriptEvent], None]
HostKeyVerifier = Callable[[domain.HostKeyPrompt], domain.HostKeyDecision]